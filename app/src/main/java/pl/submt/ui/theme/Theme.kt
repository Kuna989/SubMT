/**
 * App theme.
 *
 * @param darkTheme follows the system setting by default; the Settings screen (B6) can override it.
 * @param dynamicColor uses Material You wallpaper colors on Android 12+. Off by default
 * so the brand palette is shown; can be exposed as a user setting.
 */
@Composable
fun SubMtTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme: ColorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = SubMtTypography,
        content = content,
    )
}
